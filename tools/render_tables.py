"""Write the sweep tables into the README from the experiment output.

The headline figures in the prose are guarded by anchor phrases in
`tools/check_numbers.py`. The tables are guarded differently: they are generated from
`docs/experiments/*.json` and regenerated by `make verify`, so CI's `git diff --exit-code`
fails if what is committed no longer matches the measurements.

They are written inside fenced blocks rather than as markdown tables, for the same reason
the CLI transcript is fenced: this is output, not prose, and the number checker is right
to leave it alone.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

OPEN = "<!-- table:{name} -->\n```text\n"
CLOSE = "```\n<!-- /table:{name} -->"

ROOT = Path(__file__).resolve().parent.parent
EXPERIMENTS = ROOT / "docs" / "experiments"
README = ROOT / "README.md"


def load(name: str) -> dict:
    path = EXPERIMENTS / name
    if not path.exists():
        raise SystemExit(f"missing {path.relative_to(ROOT)}, run `make bench` first")
    return json.loads(path.read_text())


def table(headers: list[str], widths: list[int], rows: list[list[str]],
          left: int = -1) -> str:
    """Right-align every column except `left`, which is a label rather than a number."""
    def pad(cell: str, index: int, width: int) -> str:
        return cell.ljust(width) if index == left else cell.rjust(width)

    def line(cells: list[str]) -> str:
        return "".join(
            pad(c, i, w) for i, (c, w) in enumerate(zip(cells, widths, strict=True))
        ).rstrip()

    head = line(headers)
    return "\n".join([head, "-" * max(len(head), *(len(line(r)) for r in rows)), 
                      *(line(r) for r in rows)])


def e1_table() -> str:
    data = load("e1.json")
    rows = [
        [r["paginator"], r["write_mode"], str(r["pages"]), str(r["duplicates"]),
         str(r["skipped"]), str(r["new_rows_seen"]),
         "yes" if r["model_agrees"] else "NO"]
        for r in data["results"]
    ]
    return table(
        ["paginator", "writer", "pages", "twice", "never", "new seen", "model"],
        [12, 10, 8, 8, 8, 10, 8], rows, left=0,
    )


def e2_table() -> str:
    data = load("e2.json")
    rows = [
        [f"{m['depth']:,}", f"{m['offset_ms']:.3f}", f"{m['keyset_ms']:.3f}",
         f"{m['ratio']:.1f}x", f"{m['rows_read_by_offset']:,}",
         f"{m['us_per_row_read']:.3f}"]
        for m in data["measurements"]
    ]
    return table(
        ["depth", "offset ms", "keyset ms", "ratio", "rows read", "us/row"],
        [11, 12, 12, 10, 13, 10], rows,
    )


def e3_table() -> str:
    data = load("e3.json")
    rows = [
        [f"{m['rows']:,}", f"{m['offset_seconds']:.3f}", f"{m['keyset_seconds']:.3f}",
         f"{m['time_ratio']:.1f}x", f"{m['read_amplification']:.1f}x"]
        for m in data["measurements"]
    ]
    return table(
        ["rows", "offset s", "keyset s", "ratio", "rows read"],
        [10, 11, 11, 9, 12], rows,
    )


TABLES = {"e1": e1_table, "e2": e2_table, "e3": e3_table}


def main() -> None:
    text = README.read_text()
    for name, build in TABLES.items():
        # The trailing newline is optional so that an empty placeholder block - the state
        # a new table starts life in - matches on the first run.
        pattern = re.compile(
            rf"(<!-- table:{name} -->\n```text\n).*?(\n?```\n<!-- /table:{name} -->)",
            re.DOTALL,
        )
        if not pattern.search(text):
            raise SystemExit(
                f"README has no marked block for table:{name}. Add one as:\n"
                f"{OPEN.format(name=name)}{CLOSE.format(name=name)}"
            )
        replacement = f"{OPEN.format(name=name)}{build()}\n{CLOSE.format(name=name)}"
        text = pattern.sub(lambda _m, r=replacement: r, text)
    README.write_text(text)
    print(f"rendered {len(TABLES)} tables into README.md")


if __name__ == "__main__":
    main()
