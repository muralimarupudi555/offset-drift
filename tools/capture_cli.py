"""Run the tool for real and commit what it printed.

A README that quotes invented output is a README that drifts. This runs the real command
and writes what came back, exit codes included, so the block in
the documentation is a transcript rather than a description.

Regenerated by `make bench` rather than by `make verify`. The scans are deterministic -
the writer acts between pages rather than on a thread of its own - but the transcript
carries a wall-clock figure, and a gate that leaves uncommitted changes behind every time
it runs is a gate people stop reading the output of.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "cli-output.md"

INVOCATIONS = [
    ("An offset scan while rows are being deleted above the cursor",
     ["--write-mode", "delete", "--rows", "4000"]),
    ("The same writer, with keyset pagination",
     ["--paginator", "keyset", "--write-mode", "delete", "--rows", "4000"]),
    ("An offset scan while rows are being inserted above the cursor",
     ["--write-mode", "insert", "--rows", "4000"]),
    ("A scan that cannot show the effect",
     ["--write-mode", "insert", "--writes-per-page", "0"]),
]

PREAMBLE = (
    "Generated by `tools/capture_cli.py`, which runs the real command against a real "
    "scan against a real PostgreSQL and records what came back. Regenerated by "
    "`make bench`; the drift counts are deterministic and only the timing moves."
)


def main() -> None:
    sections = ["# Captured output", "", PREAMBLE, ""]
    for title, args in INVOCATIONS:
        result = subprocess.run(
            ["offset-drift", *args],
            cwd=ROOT, capture_output=True, text=True, check=False,
        )
        body = (result.stdout + result.stderr).rstrip()
        sections += [
            f"## {title}", "",
            "```console",
            f"$ offset-drift {' '.join(args)}",
            body,
            "$ echo $?", str(result.returncode),
            "```", "",
        ]
        print(f"  captured `{' '.join(args)}` -> exit {result.returncode}")

    OUT.write_text("\n".join(sections))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
